/**
 * @indigodb/migrator — `introspectResolvedSchema` unit + round-trip suite.
 *
 * Mirrors `appliability.mjs`'s style: plain Node, no test framework, PGlite
 * (`@electric-sql/pglite`) as the real PostgreSQL engine driving every
 * assertion — introspection reads a live catalog, so hand-built row fixtures
 * would only prove the parsing code agrees with itself, not with PostgreSQL.
 *
 * Round-trip (B.5/B.10) is the strongest correctness proof in this suite:
 * for every fixture schema in the corpus, `renderPushSql` -> apply to a real
 * PGlite instance -> `introspectResolvedSchema` -> `planMigration(introspected,
 * sameSchemaResolved)` must be an EMPTY plan (zero statements, zero
 * diagnostics). That is the only test that proves the primitive actually
 * inverts the renderer, not merely that it doesn't throw.
 */

import { readdirSync, readFileSync } from "node:fs";
import { deepStrictEqual, strictEqual, ok } from "node:assert";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";
import { parse, resolve } from "@indigodb/core";
import { withDatabase, assertApplies } from "./pg-harness.mjs";
import { introspectResolvedSchema, planMigration, renderPushSql } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, "fixtures");

let failures = 0;

async function check(name, fn) {
  try {
    await fn();
    console.log(`  ok   ${name}`);
  } catch (err) {
    failures++;
    console.error(`  FAIL ${name}`);
    console.error(String(err.message).split("\n").slice(0, 30).join("\n"));
  }
}

console.log("migrator introspect: introspectResolvedSchema unit + round-trip suite");

/** Adapts a PGlite instance to the `IntrospectionQuery` contract. */
function queryOf(db) {
  return (sql, params) => db.query(sql, params);
}

// ─── B.1: type/nativeType inversion table ────────────────────────────────────

await check("type inversion: base scalar table (text, integer, bigint, double precision, boolean, timestamptz, jsonb, bytea)", async () => {
  await withDatabase(async (db) => {
    await assertApplies(
      db,
      `CREATE TABLE "T" (
        "a" text NOT NULL,
        "b" integer NOT NULL,
        "c" bigint NOT NULL,
        "d" double precision NOT NULL,
        "e" boolean NOT NULL,
        "f" timestamptz NOT NULL,
        "g" jsonb NOT NULL,
        "h" bytea NOT NULL,
        "i" numeric NOT NULL
      );`,
    );
    const schema = await introspectResolvedSchema(queryOf(db));
    const table = schema.tables.find((t) => t.dbName === "T");
    ok(table, "table T introspected");
    const byName = Object.fromEntries(table.columns.map((c) => [c.dbName, c]));
    strictEqual(byName.a.type, "String");
    strictEqual(byName.b.type, "Int");
    strictEqual(byName.c.type, "BigInt");
    strictEqual(byName.d.type, "Float");
    strictEqual(byName.e.type, "Boolean");
    strictEqual(byName.f.type, "DateTime");
    strictEqual(byName.g.type, "Json");
    strictEqual(byName.h.type, "Bytes");
    strictEqual(byName.i.type, "Decimal");
    // Bare `numeric` (no explicit precision/scale) never recovers a nativeType override.
    strictEqual(byName.i.nativeType, undefined);
  });
});

