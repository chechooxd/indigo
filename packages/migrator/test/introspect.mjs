await check("default parsing: now(), gen_random_uuid(), string literal, enum-cast literal", async () => {
  await withDatabase(async (db) => {
    await assertApplies(
      db,
      `DO $$ BEGIN CREATE TYPE "Status" AS ENUM ('ACTIVE', 'INACTIVE'); EXCEPTION WHEN duplicate_object THEN null; END $$;
       CREATE TABLE "T" (
         "createdAt" timestamptz NOT NULL DEFAULT now(),
         "token" uuid NOT NULL DEFAULT gen_random_uuid(),
         "email" text NOT NULL DEFAULT ''::text,
         "status" "Status" NOT NULL DEFAULT 'ACTIVE'::"Status"
       );`,
    );
    const schema = await introspectResolvedSchema(queryOf(db));
    const byName = Object.fromEntries(schema.tables[0].columns.map((c) => [c.dbName, c]));
    deepStrictEqual(byName.createdAt.default, { kind: "function", name: "now" });
    deepStrictEqual(byName.token.default, { kind: "function", name: "uuid" });
    deepStrictEqual(byName.email.default, { kind: "value", value: "" });
    deepStrictEqual(byName.status.default, { kind: "value", value: "ACTIVE" });
    strictEqual(byName.status.isEnum, true);
    strictEqual(byName.status.type, "Status");
  });
});

// ─── B.2: unmappable pg type throws ──────────────────────────────────────────

await check("unmappable pg type throws, naming table.column and the type", async () => {
  await withDatabase(async (db) => {
    await assertApplies(db, `CREATE TABLE "T" ("span" interval NOT NULL);`);
    let threw = false;
    try {
      await introspectResolvedSchema(queryOf(db));
    } catch (err) {
      threw = true;
      ok(/T\.span/.test(err.message), `error names table.column: ${err.message}`);
      ok(/interval/.test(err.message), `error names the type: ${err.message}`);
    }
    ok(threw, "expected introspectResolvedSchema to throw on an unmappable type");
  });
});

