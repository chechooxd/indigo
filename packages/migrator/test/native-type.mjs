/**
 * @indigodb/migrator — native type override (`@db.X`) direct unit coverage.
 *
 * `renderColumn` is exercised directly against synthetic `ResolvedColumn`
 * objects (not through a golden fixture) to pin the exact branch ordering
 * design.md requires: the `nativeType` branch is inserted AFTER the
 * `autoincrement`/IDENTITY check, so IDENTITY always wins over an override.
 * Full-statement-level coverage (CREATE TABLE / ADD COLUMN) lives in the
 * golden fixture `test/fixtures/native-type-override/`.
 */

import { deepStrictEqual } from "node:assert";
import { renderColumn } from "../dist/index.js";

let failures = 0;

function check(name, fn) {
  try {
    fn();
    console.log(`  ok   ${name}`);
  } catch (err) {
    failures++;
    console.error(`  FAIL ${name}`);
    console.error(String(err.message).split("\n").slice(0, 30).join("\n"));
  }
}

/** Minimal `ResolvedColumn` builder — only the fields `renderColumn` reads. */
function col(overrides = {}) {
  return {
    name: "field",
    dbName: "field",
    type: "String",
    isEnum: false,
    nullable: false,
    isPk: false,
    unique: false,
    autoincrement: false,
    ...overrides,
  };
}

console.log("native-type: renderColumn unit cases");

check("VarChar with one arg renders VARCHAR(255)", () => {
  const c = col({ name: "bio", dbName: "bio", nativeType: { name: "VarChar", args: ["255"] } });
  deepStrictEqual(renderColumn(c), `"bio" VARCHAR(255) NOT NULL`);
});

check("Uuid with zero args renders bare UUID, no parens", () => {
  const c = col({ name: "id", dbName: "id", nativeType: { name: "Uuid", args: [] } });
  deepStrictEqual(renderColumn(c), `"id" UUID NOT NULL`);
});

check("Numeric with two args renders NUMERIC(10,2)", () => {
  const c = col({ name: "price", dbName: "price", type: "Decimal", nativeType: { name: "Numeric", args: ["10", "2"] } });
  deepStrictEqual(renderColumn(c), `"price" NUMERIC(10,2) NOT NULL`);
});

check("column without nativeType renders exactly as mapScalarToPg today (regression)", () => {
  const c = col({ name: "name", dbName: "name", type: "String" });
  deepStrictEqual(renderColumn(c), `"name" text NOT NULL`);
});

check("autoincrement AND nativeType both present: IDENTITY wins, override is ignored", () => {
  const c = col({
    name: "id",
    dbName: "id",
    type: "Int",
    autoincrement: true,
    nativeType: { name: "Uuid", args: [] },
  });
  deepStrictEqual(renderColumn(c), `"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL`);
});

if (failures > 0) {
  console.error(`\nnative-type: ${failures} failure(s)`);
  process.exit(1);
}
console.log("\nnative-type: all green");
