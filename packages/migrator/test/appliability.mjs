/**
 * @indigodb/migrator — PostgreSQL appliability suite.
 *
 * Mirrors `migrator.mjs`'s style: plain Node, no test framework. Where
 * `migrator.mjs` pins exact generated SQL TEXT against golden files, this
 * suite proves the SAME fixtures' SQL actually EXECUTES against a real
 * PostgreSQL engine — `@electric-sql/pglite` (`PostgreSQL 18.3`, WASM,
 * in-process, no Docker/network dependency).
 *
 * SCOPE: "appliability" — the emitted DDL applies without error on a
 * single-connection engine. This is NOT a proof of production correctness
 * under concurrency: concurrent deploys, advisory locking and
 * connection-pool behaviour are explicitly OUT OF SCOPE and are not
 * simulated here.
 *
 * Drives the shipped migrator exports exactly as `@indigodb/cli`'s
 * `migrate-runner.ts` does: `planMigration` → `renderMigrationSql` →
 * `splitMigrationSql` (via `pg-harness.mjs`'s `applyPlan`) → `renderPushSql`.
 * No production code changes; no parallel re-implementation of the phase
 * split.
 */

import { readdirSync } from "node:fs";
import { deepStrictEqual } from "node:assert";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";
import { loadFixture } from "./lib.mjs";
import { withDatabase, applyPlan, assertApplies, assertRejects } from "./pg-harness.mjs";
import { planMigration, renderMigrationSql, renderPushSql, splitMigrationSql } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, "fixtures");

let failures = 0;

async function check(name, fn) {
  try {
    await fn();
    console.log(`  ok   ${name}`);
  } catch (err) {
    failures++;
    console.error(`  FAIL ${name}`);
    console.error(String(err.message).split("\n").slice(0, 30).join("\n"));
  }
}

console.log("migrator appliability: PostgreSQL execution suite (PGlite, in-process)");
console.log(
  'Scope: "appliability" — the emitted SQL executes without error on a single-connection\n' +
    "engine. This is NOT a proof of production correctness under concurrency: concurrent\n" +
    "deploys, advisory locking, and connection-pool behaviour stay explicitly out of scope.\n",
);

const REFUSAL_FIXTURES = new Set(["enum-value-removed", "map-rename-ambiguous", "not-null-no-default"]);

const cases = readdirSync(fixturesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

/** Applies a seed plan's statements one at a time (fresh DB, `prev` construction only). */
async function seedDatabase(db, prev) {
  if (!prev) return;
  const seedPlan = planMigration(null, prev);
  for (const stmt of seedPlan.statements) {
    try {
      await db.exec(stmt.sql);
    } catch (err) {
      throw new Error(`seeding prev failed on statement:\n${stmt.sql}\n${err.message}`);
    }
  }
}

// ─── Harness self-test — proves the executed-statement counter and error ────
// path are real, so "zero executed" in the refusal-fixture assertions below
// cannot mean "errors were silently swallowed".

await check("harness self-test: invalid DDL rejects, nothing counted as executed", async () => {
  await withDatabase(async (db) => {
    let executed = 0;
    try {
      executed = await applyPlan(db, 'CREATE TABLE "X" ("id" nosuchtype);');
    } catch {
      executed = 0;
    }
    if (executed !== 0) {
      throw new Error(`expected the invalid statement to throw before counting; got executed=${executed}`);
    }
  });
});

// ─── Phase 3: historical-bug regressions ────────────────────────────────────
//
// The RED for this suite: writing `assertApplies` against deliberately
// hand-constructed PRE-FIX SQL fails — PGlite rejects it with the exact
// historical error. That failure is the RED; inverting to `assertRejects`
// (pre-fix SQL) + `assertApplies` (current, fixed emission) is the GREEN.
// Captured RED, verbatim, from this exact construction:
//   relation "User" does not exist
//   unsafe use of new value "B" of enum type "S"

const LEGACY_FK_ORDER_SQL = [
  'CREATE TABLE "Post" (',
  '  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
  '  "userId" integer NOT NULL,',
  '  PRIMARY KEY ("id"),',
  '  CONSTRAINT "Post_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User" ("id")',
  ");",
  'CREATE TABLE "User" (',
  '  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
  '  PRIMARY KEY ("id")',
  ");",
].join("\n");

await check(
  "regression: FK-ordering stays fixed — pre-fix inline FK rejected, current fk-order-declaration emission applies",
  async () => {
    await withDatabase(async (db) => {
      await assertRejects(db, LEGACY_FK_ORDER_SQL, /relation "User" does not exist/);
    });
    await withDatabase(async (db) => {
      const { next } = loadFixture(join(fixturesDir, "fk-order-declaration"));
      const plan = planMigration(null, next);
      const executed = await applyPlan(db, renderMigrationSql(plan));
      if (executed === 0) throw new Error("expected the current emission to execute at least one statement");
    });
  },
);

const LEGACY_ENUM_SINGLE_TX_SQL = [
  "BEGIN;",
  "ALTER TYPE \"S\" ADD VALUE IF NOT EXISTS 'B';",
  "ALTER TABLE \"T\" ALTER COLUMN \"s\" SET DEFAULT 'B'::\"S\";",
  "COMMIT;",
].join("\n");

await check(
  "regression: enum ADD VALUE stays split — pre-fix single-transaction use rejected, enum-add-value-and-use split emission applies",
  async () => {
    const dir = join(fixturesDir, "enum-add-value-and-use");
    const { prev, next } = loadFixture(dir);

    await withDatabase(async (db) => {
      await seedDatabase(db, prev);
      await assertRejects(db, LEGACY_ENUM_SINGLE_TX_SQL, /unsafe use of new value "B" of enum type "S"/);
    });
    await withDatabase(async (db) => {
      await seedDatabase(db, prev);
      const plan = planMigration(prev, next);
      const executed = await applyPlan(db, renderMigrationSql(plan));
      if (executed !== 2) {
        throw new Error(`expected 2 executed units (pre-transaction ADD VALUE + transactional body), got ${executed}`);
      }
    });
  },
);

// ─── Phase 4: fixture replay — every fixture applies against real PostgreSQL ─

for (const name of cases) {
  const dir = join(fixturesDir, name);
  const { prev, next } = loadFixture(dir);
  const plan = planMigration(prev, next);
  const isRefusal = REFUSAL_FIXTURES.has(name);

  await check(`${name}: prev applies, plan applies (or refuses cleanly)`, async () => {
    await withDatabase(async (db) => {
      await seedDatabase(db, prev);
      const sql = renderMigrationSql(plan);
      let executed;
      try {
        executed = await applyPlan(db, sql);
      } catch (err) {
        throw new Error(`fixture "${name}" failed to apply:\n${err.message}`);
      }
      if (isRefusal) {
        if (plan.diagnostics.length === 0) throw new Error(`expected diagnostics for refusal fixture "${name}"`);
        if (plan.statements.length !== 0) throw new Error(`expected zero statements for refusal fixture "${name}"`);
        if (sql !== "") throw new Error(`expected empty renderMigrationSql for refusal fixture "${name}"`);
        if (executed !== 0) throw new Error(`expected zero executed statements for refusal fixture "${name}", got ${executed}`);
      } else {
        if (plan.diagnostics.length !== 0) throw new Error(`unexpected diagnostics for fixture "${name}"`);
      }
    });
  });

  await check(`${name}: round-trip invariant — splitMigrationSql(renderMigrationSql(plan)) matches plan.statements phases`, async () => {
    const sql = renderMigrationSql(plan);
    const { preTransaction } = splitMigrationSql(sql);
    const expectedPreTransaction = plan.statements.filter((s) => s.phase === "pre-transaction").map((s) => s.sql);
    deepStrictEqual(preTransaction, expectedPreTransaction);
  });

  await check(`${name}: renderPushSql is idempotent — applied twice against a clean DB, both succeed`, async () => {
    await withDatabase(async (db) => {
      const pushSql = renderPushSql(next);
      await assertApplies(db, pushSql);
      await assertApplies(db, pushSql);
    });
  });
}

// ─── Phase 4.6: fixture isolation ────────────────────────────────────────────
//
// Two distinct fixtures that both declare a same-named `Table "User"`: run
// each in its OWN `withDatabase` call, back to back. If isolation were
// procedural (shared instance + reset) instead of structural (fresh
// instance per call), a contamination bug would surface here as a
// duplicate-object error on the second fixture.

await check("fixture isolation: two fixtures reusing the same object name don't interfere", async () => {
  const first = loadFixture(join(fixturesDir, "fk-order-declaration"));
  const second = loadFixture(join(fixturesDir, "optional-column-added"));

  await withDatabase(async (db) => {
    const plan = planMigration(null, first.next);
    await applyPlan(db, renderMigrationSql(plan));
  });
  await withDatabase(async (db) => {
    await seedDatabase(db, second.prev);
    const plan = planMigration(second.prev, second.next);
    const executed = await applyPlan(db, renderMigrationSql(plan));
    if (executed === 0) throw new Error("expected the second fixture to still apply cleanly in its own database");
  });
});

if (failures > 0) {
  console.error(`\nmigrator appliability: ${failures} failure(s)`);
  process.exit(1);
}
console.log("\nmigrator appliability: all green");
