/**
 * @indigodb/client — runtime index-awareness suite (`named-index-followups`).
 *
 * Proves:
 *   1. `delegate.indexes` exposes declared index metadata (`__meta[Model].indexes`)
 *      and defaults to `[]` for hand-authored delegates that omit it.
 *   2. `delegate.explain(args)` runs real PostgreSQL `EXPLAIN (FORMAT JSON)`
 *      on the exact parameterized `findMany` query against in-process PGlite
 *      and reports `sql`, `params`, `scanTypes`, `indexNames`, `usesIndex`,
 *      `totalCost`, and the raw `plan` node for both sequential and indexed plans.
 */

import { strictEqual, deepStrictEqual, ok } from "node:assert";
import { PGlite } from "@electric-sql/pglite";
import { ModelDelegate } from "../dist/index.js";

let failures = 0;
async function check(name, fn) {
  try {
    await fn();
    console.log(`  ok   ${name}`);
  } catch (err) {
    failures++;
    console.error(`  FAIL ${name}`);
    console.error(String(err.stack ?? err.message).split("\n").slice(0, 25).join("\n"));
  }
}

console.log("client index-awareness suite");

await check("delegate.indexes exposes declared indexes and defaults to [] when absent", () => {
  const exec = async () => [];
  const bare = new ModelDelegate(
    {
      name: "Bare",
      table: "Bare",
      fields: { id: { db: "id", pk: true } },
      uniqueGroups: [["id"]],
    },
    exec,
  );
  deepStrictEqual(bare.indexes, []);

  const withIndexes = new ModelDelegate(
    {
      name: "Account",
      table: "Account",
      fields: { id: { db: "id", pk: true }, email: { db: "email" } },
      uniqueGroups: [["id"]],
      indexes: [
        { fields: ["email"], unique: false, name: "account_email_idx" },
        { fields: [], unique: true, name: "account_lower_email_key", expression: "lower(email)" },
      ],
    },
    exec,
  );
  strictEqual(withIndexes.indexes.length, 2);
  strictEqual(withIndexes.indexes[0].name, "account_email_idx");
  strictEqual(withIndexes.indexes[1].expression, "lower(email)");
});

await check("delegate.explain() runs live PostgreSQL EXPLAIN (FORMAT JSON) and detects Seq Scan vs Index Scan", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE TABLE "Account" (
        "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "org_id" integer NOT NULL,
        "slug" text NOT NULL,
        "email" text NOT NULL,
        "deleted_at" timestamptz
      );
      CREATE INDEX "account_email_idx" ON "Account" ("email");
      CREATE UNIQUE INDEX "account_active_email_key" ON "Account" ("email") WHERE deleted_at IS NULL;
      CREATE UNIQUE INDEX "account_lower_email_key" ON "Account" (lower(email));
    `);
    await db.query(
      `INSERT INTO "Account" ("org_id", "slug", "email") VALUES (1, 'a', 'alice@example.com'), (1, 'b', 'bob@example.com')`,
    );

    const exec = async (sql, params) => (await db.query(sql, params)).rows;
    const delegate = new ModelDelegate(
      {
        name: "Account",
        table: "Account",
        fields: {
          id: { db: "id", pk: true, numeric: true },
          orgId: { db: "org_id", numeric: true },
          slug: { db: "slug" },
          email: { db: "email" },
          deletedAt: { db: "deleted_at" },
        },
        uniqueGroups: [["id"]],
        indexes: [
          { fields: ["email"], unique: false, name: "account_email_idx" },
          { fields: ["email"], unique: true, name: "account_active_email_key", where: "deleted_at IS NULL" },
          { fields: [], unique: true, name: "account_lower_email_key", expression: "lower(email)" },
        ],
      },
      exec,
    );

    // Unfiltered full scan -> Seq Scan, usesIndex === false
    const seqPlan = await delegate.explain({});
    ok(seqPlan.sql.startsWith("SELECT "), `expected SELECT SQL, got: ${seqPlan.sql}`);
    deepStrictEqual(seqPlan.params, []);
    strictEqual(seqPlan.usesIndex, false, `expected Seq Scan without WHERE, got: ${JSON.stringify(seqPlan)}`);
    ok(seqPlan.scanTypes.includes("Seq Scan"), `expected Seq Scan in ${JSON.stringify(seqPlan.scanTypes)}`);
    strictEqual(typeof seqPlan.totalCost, "number");

    // Disable seqscan so Postgres chooses the real index even on a 2-row table
    await db.exec("SET enable_seqscan = off;");
    const idxPlan = await delegate.explain({ where: { email: "alice@example.com" } });
    deepStrictEqual(idxPlan.params, ["alice@example.com"]);
    strictEqual(idxPlan.usesIndex, true, `expected index scan, got: ${JSON.stringify(idxPlan)}`);
    ok(
      idxPlan.indexNames.includes("account_email_idx"),
      `expected account_email_idx in ${JSON.stringify(idxPlan.indexNames)}`,
    );
  } finally {
    await db.close();
  }
});

if (failures > 0) {
  console.error(`\nindex-awareness: ${failures} failure(s)`);
  process.exit(1);
}
console.log("\nindex-awareness: all passed");
